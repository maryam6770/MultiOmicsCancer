#' Simulated MultiAssayExperiment for MultiOmicsCancer examples
#'
#' A small simulated dataset containing methylation and expression data
#' for 30 samples (20 primary tumours and 10 solid-tissue normals), used
#' in the package vignette and examples. The data are entirely simulated
#' and do not correspond to real patients.
#'
#' @format A \code{MultiAssayExperiment} object with 30 samples and two
#'   experiments:
#' \describe{
#'   \item{expression}{A \code{SummarizedExperiment} with 8 genes and
#'     30 samples. Assay name: \code{expression}.}
#'   \item{methylation}{A \code{SummarizedExperiment} with 50 CpGs and
#'     30 samples. Assay name: \code{methylation}.}
#' }
#'   The \code{colData} contains the columns \code{sampleID},
#'   \code{patientID}, \code{sample_type}, \code{OS.time}, and \code{OS}.
#'
#' @details
#' The dataset was generated with \code{set.seed(123)}. Expression values
#' were drawn from a normal distribution with mean 5 and standard deviation
#' 2. Methylation beta values were drawn from a uniform distribution between
#' 0.1 and 0.9, and an offset of 0.2 was added to the first 10 CpGs in the
#' tumour samples to introduce a tumour-vs-normal difference. Survival times
#' and event indicators were simulated independently of the omics data; they
#' are included only so that survival functions in the package can be
#' demonstrated. The script that generates the dataset is provided in
#' \code{inst/scripts/make_example_mae.R}.
#'
#' @source Simulated data, generated by the package authors. No real patient
#'   data were used.
#'
#' @name example_mae
#' @docType data
#' @keywords datasets
#' @examples
#' data(example_mae)
